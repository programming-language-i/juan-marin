def suma (a,b):
    return a + b

def resta (a,b):
    return a - b


def multi (a,b):
    return a * b


resultado_suma = suma(1,2)
resultado_resta = resta(2,3)
resultado_multi = multi(1,9)

print(f"Resultado suma {resultado_suma}")
print(f"Resultado resta {resultado_resta}")
print(f"Resultado multiplicación {resultado_multi}")
